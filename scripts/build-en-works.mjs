#!/usr/bin/env node
/** Import only WEB (engwebp). Never rebuild or write any Mandarin work. */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";
import { importTs, root } from "./lib/corpus.mjs";
import { parseEnglishUsfmBook } from "./lib/english-usfm.mjs";

export const SOURCE_URL = "https://ebible.org/Scriptures/engwebp_usfm.zip";
export const SOURCE_SHA256 = "a155940bdba087cdbccb0f6737c036de9884bc5a3b8da2e82c2970d8ed26c1ba";
const ID = "en-bible-web";
// Editorial placement for an unabridged native English edition, not a Mandarin measurement.
const LEVEL = 9;

async function main() {
  const cache = path.join(root, "node_modules/.cache/duki-works");
  fs.mkdirSync(cache, { recursive: true });
  const archive = path.join(cache, "engwebp_usfm.zip");
  if (!fs.existsSync(archive)) {
    if (process.argv.includes("--offline")) throw new Error("English WEB source not cached; see docs/english-long-works.md");
    execFileSync("curl", ["-fL", "--retry", "2", "-A", "Mozilla/5.0", SOURCE_URL, "-o", archive], { stdio: "inherit" });
  }
  const hash = createHash("sha256").update(fs.readFileSync(archive)).digest("hex");
  if (hash !== SOURCE_SHA256) throw new Error(`WEB source changed (${hash}); review the edition before updating the pin.`);
  // Read archive members without extracting files or executing anything from the archive.
  const files = execFileSync("unzip", ["-Z1", archive], { encoding: "utf8" }).trim().split(/\r?\n/)
    .filter((f) => /^\d\d-[A-Z0-9]+engwebp\.usfm$/.test(f) && !f.startsWith("00-")).sort();
  if (files.length !== 66) throw new Error(`Expected 66 books, got ${files.length}`);
  const { segment } = await importTs(`export { segment } from ${JSON.stringify(path.join(root, "src/lib/segment.ts"))};`, "en-work-segment");
  const vocab = new Map();
  const bodies = [];
  const sections = files.map((file, i) => {
    const book = parseEnglishUsfmBook(execFileSync("unzip", ["-p", archive, file], { encoding: "utf8", maxBuffer: 12 * 1024 * 1024 }));
    const chapters = book.chapters.map((ch, index) => {
      if (ch.n !== index + 1) throw new Error(`Nonconsecutive chapters in ${book.code}`);
      const tokens = segment(ch.body, () => false, 8, "en").filter((t) => t.isWord);
      for (const token of tokens) vocab.set(token.key, (vocab.get(token.key) ?? 0) + 1);
      const key = `${book.code}.${ch.n}`;
      const title = `${book.name} ${ch.n}`;
      if (!/^[A-Z0-9]+\.\d+$/.test(key)) throw new Error(`Invalid key: ${key}`);
      bodies.push({ key, title, body: ch.body });
      return { key, title, label: String(ch.n), chars: 0, words: tokens.length, level: LEVEL };
    });
    return { key: book.code, title: book.name, part: i < 39 ? "Old Testament" : "New Testament", chars: 0,
      words: chapters.reduce((n, ch) => n + ch.words, 0), level: LEVEL, chapters };
  });
  if (bodies.length !== 1189 || sections[0].key !== "GEN" || sections[65].key !== "REV") throw new Error("Incomplete WEB Bible");
  const words = sections.reduce((n, s) => n + s.words, 0);
  const dir = path.join(root, "public/works", ID);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "toc.json"), JSON.stringify({ id: ID, sections }));
  for (const chapter of bodies) fs.writeFileSync(path.join(dir, `${chapter.key}.json`), JSON.stringify(chapter));
  const sorted = [...vocab].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], "en")).slice(0, 4000);
  fs.writeFileSync(path.join(dir, "profile.json"), JSON.stringify({ tokens: words, words: sorted.map(([w]) => w), counts: sorted.map(([, c]) => c) }));
  const stats = { [ID]: { id: ID, chapters: bodies.length, sections: sections.length, chars: 0, words,
    level: LEVEL, score: LEVEL, levelMin: LEVEL, levelMax: LEVEL, levelLow: LEVEL, levelHigh: LEVEL, firstKey: "GEN.1" } };
  fs.writeFileSync(path.join(root, "src/data/en-works.generated.ts"), '// Generated by scripts/build-en-works.mjs — do not edit by hand.\nimport type { WorkStats } from "../lib/works";\n\nexport const EN_WORK_STATS: Record<string, WorkStats> = ' + JSON.stringify(stats, null, 2) + ";\n");
  console.log(`${ID}: ${sections.length} books, ${bodies.length} chapters, ${words.toLocaleString("en-US")} words; source SHA-256 ${hash}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
