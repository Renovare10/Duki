#!/usr/bin/env node
/**
 * Precomputes difficulty for the built-in catalog so library cards can show a
 * level badge without shipping HSK lists or re-analysing texts at runtime.
 *   node scripts/build-text-meta.mjs   → src/data/text-meta.ts
 * src/data/text-meta.test.ts fails if a catalog text changes without a rebuild.
 */
import fs from "node:fs";
import path from "node:path";
import { analyze, loadAppModules, root } from "./lib/corpus.mjs";

const app = await loadAppModules();
const rows = app.CATALOG.filter((t) => t.body.trim()).map((t) => {
  const a = analyze(app, t.body);
  return [t.id, [a.level, Math.round(a.score * 100), a.chars]];
});
const body = rows.map(([id, v]) => `  ${JSON.stringify(id)}: [${v.join(", ")}],`).join("\n");
const out =
  "// Generated by scripts/build-text-meta.mjs — do not edit by hand.\n" +
  "// id → [level 1–10, level score × 100 (for ordering), Han characters]\n" +
  "export const TEXT_META: Record<string, readonly [number, number, number]> = {\n" +
  body +
  "\n};\n";
fs.writeFileSync(path.join(root, "src/data/text-meta.ts"), out);
console.log(`wrote src/data/text-meta.ts (${rows.length} texts)`);
